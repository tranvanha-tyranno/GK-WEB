async (page) => {
  const checks = [], errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const check = (name, detail) => checks.push({ name, status: 'PASS', detail });
  const assert = (value, detail) => { if (!value) throw new Error(detail); };
  await page.setViewportSize({width:1440,height:900});
  await page.goto('http://localhost:8080/chat');
  await page.getByText('Đã kết nối',{exact:true}).waitFor();
  const tool = async name => {
    if (await page.locator('#tools-panel').isHidden()) await page.getByRole('button',{name:'Mở công cụ phòng',exact:true}).click();
    await page.getByRole('button',{name,exact:true}).click();
  };
  if (await page.evaluate(() => document.documentElement.dataset.theme === 'dark')) await tool('Bật giao diện sáng');
  if (await page.locator('#toggle-compact').getAttribute('aria-pressed') === 'true') await tool('Thu gọn');
  await page.getByRole('button',{name:'# Trò chuyện chung',exact:true}).click();
  await page.waitForTimeout(500);
  await page.getByRole('heading',{name:'Trò chuyện chung',exact:true}).click();
  assert(await page.locator('#tools-panel').isHidden() && await page.locator('#search-panel').isHidden(),'Secondary tools must start closed');
  assert(await page.locator('.chat-header button:visible').count() === 2,'Header contains extra visible buttons');
  assert(await page.locator('.members-panel, .room-welcome, .chat-tools').count() === 0,'Redundant panels still present');
  assert(await page.locator('.message-actions').evaluateAll(nodes=>nodes.every(node=>getComputedStyle(node).opacity==='0')),'Message actions visible at rest');
  const keyboardMessage = page.locator('.message').last();
  await keyboardMessage.focus();
  assert(await keyboardMessage.locator('.message-actions').evaluate(node=>getComputedStyle(node).opacity==='1'),'Keyboard focus did not reveal message tools');
  await page.getByRole('heading',{name:'Trò chuyện chung',exact:true}).click();
  check('Bề mặt trò chuyện gọn','Hai nút trên đầu phòng, tìm kiếm và menu đóng, thao tác tin ẩn khi chưa chọn.');
  await page.getByRole('button',{name:'Mở công cụ phòng',exact:true}).click();
  await page.keyboard.press('Escape');
  assert(await page.locator('#tools-panel').isHidden(),'Escape did not close menu');
  assert(await page.locator('#toggle-tools').evaluate(node=>node===document.activeElement),'Menu trigger lost keyboard focus');
  await page.getByRole('button',{name:'Mở công cụ phòng',exact:true}).click();
  await page.getByRole('heading',{name:'Trò chuyện chung',exact:true}).click();
  assert(await page.locator('#tools-panel').isHidden(),'Outside click did not close menu');
  check('Menu công cụ','Mở bằng nút góc phải; đóng khi bấm ngoài/Esc, trả tiêu điểm bàn phím đúng.');
  const box = page.getByRole('textbox',{name:'Tin nhắn của bạn',exact:true});
  await box.fill('Bản nháp tiếng Việt 28/10');
  await page.getByRole('button',{name:'# Kỹ thuật',exact:true}).click();
  await box.fill('Nháp phòng kỹ thuật');
  await page.getByRole('button',{name:'# Trò chuyện chung',exact:true}).click();
  assert(await box.inputValue() === 'Bản nháp tiếng Việt 28/10','Room draft lost');
  await page.reload(); await page.getByText('Đã kết nối',{exact:true}).waitFor();
  assert(await box.inputValue() === 'Bản nháp tiếng Việt 28/10','Reload draft lost');
  check('Bản nháp riêng theo phòng và tải lại','Hai phòng giữ nội dung độc lập trong cùng thẻ.');
  await box.fill('Kiểm tra tiếng Việt: kỹ thuật và ý tưởng mới');
  await page.getByRole('button',{name:'Gửi tin nhắn',exact:true}).click();
  const sent = page.locator('.message').filter({hasText:'Kiểm tra tiếng Việt: kỹ thuật và ý tưởng mới'}).last();
  await sent.waitFor();
  await page.waitForTimeout(300);
  assert(await page.evaluate(()=>sessionStorage.getItem('relay:draft:1:1'))===null,'Accepted send remained in persisted draft');
  check('Gửi và xóa bản nháp đã xác nhận','Tin có echo; bản nháp đã gửi được xóa.');
  await page.getByRole('button',{name:'Tìm tin nhắn',exact:true}).click();
  await page.getByRole('searchbox',{name:'Tìm tin nhắn',exact:true}).fill('ky thuat va y tuong');
  assert(await page.locator('.message').count()>=1,'Accent-insensitive search failed');
  await page.getByRole('searchbox').fill('khongco_ketqua_281026');
  await page.getByText('Không tìm thấy tin nhắn phù hợp. Thử từ khóa khác hoặc xóa tìm kiếm.',{exact:true}).waitFor();
  await page.keyboard.press('Escape');
  check('Tìm không dấu và trạng thái rỗng','Tìm được kỹ thuật bằng ky thuat; Esc xóa tìm kiếm.');
  await sent.hover();
  await sent.getByRole('button',{name:'Trả lời tin nhắn của Alice Nguyen',exact:true}).click();
  await box.fill('Đã nhận, mình cùng làm nhé!');
  assert(await page.locator('#reply-preview').isVisible(),'Reply preview missing');
  await page.getByRole('button',{name:'Gửi tin nhắn',exact:true}).click();
  await page.locator('.message-text').filter({hasText:'> Alice Nguyen: Kiểm tra tiếng Việt'}).last().waitFor();
  await page.getByRole('button',{name:'Chọn biểu tượng cảm xúc',exact:true}).click();
  await page.getByRole('button',{name:'Ý tưởng',exact:true}).click();
  assert(await box.inputValue()==='💡','Emoji not inserted');
  await page.keyboard.press('Escape');
  await box.fill('😀'.repeat(501));
  assert(await page.getByRole('button',{name:'Gửi tin nhắn',exact:true}).isDisabled(),'Unicode limit failed');
  await box.fill('');
  check('Trả lời, biểu tượng và giới hạn Unicode','Trích dẫn gửi dạng văn bản, emoji chèn đúng, 501 mã ký tự khóa gửi.');
  await tool('Bật giao diện tối');
  await tool('Thu gọn');
  await page.reload(); await page.getByText('Đã kết nối',{exact:true}).waitFor();
  assert(await page.evaluate(()=>document.documentElement.dataset.theme==='dark'&&document.body.classList.contains('compact')),'Preferences not retained');
  await page.screenshot({path:'output/playwright/VI-chat-dark.png'});
  await tool('Bật giao diện sáng');
  await tool('Thu gọn');
  check('Sáng/tối và thu gọn','Lựa chọn còn sau tải lại.');
  const [download] = await Promise.all([page.waitForEvent('download'),tool('Xuất hội thoại')]);
  await download.saveAs('output/playwright/VI-hoi-thoai.txt');
  check('Xuất hội thoại','Tải được tệp TXT UTF-8 phòng hiện tại.');
  await page.context().grantPermissions(['clipboard-read','clipboard-write']);
  await page.locator('.message').last().hover();
  await page.locator('.message').last().getByRole('button',{name:'Sao chép tin nhắn của Alice Nguyen',exact:true}).click();
  assert((await page.evaluate(()=>navigator.clipboard.readText())).includes('Đã nhận'),'Clipboard did not contain message');
  check('Sao chép','Bộ nhớ tạm chứa đúng văn bản tin nhắn.');
  await page.context().setOffline(true); await page.evaluate(()=>window.dispatchEvent(new Event('offline')));
  await box.fill('Bản nháp lúc mất mạng');
  assert(await page.getByRole('button',{name:'Gửi tin nhắn',exact:true}).isDisabled(),'Offline send enabled');
  assert(!await box.isDisabled(),'Offline drafting unavailable');
  await page.context().setOffline(false); await page.evaluate(()=>window.dispatchEvent(new Event('online')));
  await page.getByText('Đã kết nối',{exact:true}).waitFor();
  assert(await box.inputValue()==='Bản nháp lúc mất mạng','Reconnect lost draft');
  await box.fill('');
  check('Ngoại tuyến và khôi phục','Soạn được khi ngoại tuyến, khóa gửi, bản nháp giữ sau nối lại.');
  await page.keyboard.press('Control+k');
  assert(await page.getByRole('searchbox').evaluate(el=>el===document.activeElement),'Search shortcut failed');
  await tool('Hướng dẫn và phím tắt');
  assert(await page.getByRole('dialog').isVisible(),'Help dialog did not open'); await page.keyboard.press('Escape');
  check('Phím tắt và trợ giúp','Ctrl K mở tìm kiếm, Esc đóng hộp thoại.');
  await page.getByRole('button',{name:'Đóng tìm kiếm',exact:true}).click();
  await page.getByRole('heading',{name:'Trò chuyện chung',exact:true}).click();
  await page.screenshot({path:'output/playwright/clean-chat-desktop.png'});
  for (const [width,height] of [[1440,900],[1024,768],[768,1024],[390,844],[320,740]]) {
    await page.setViewportSize({width,height});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Overflow '+width);
    assert(await page.getByRole('button',{name:'Gửi tin nhắn',exact:true}).isVisible(),'Send not visible '+width);
    assert(await box.evaluate(node => node.scrollHeight <= node.clientHeight + 1),'Empty composer scrolls at '+width);
    await page.getByRole('button',{name:'Mở công cụ phòng',exact:true}).click();
    const menuBounds = await page.locator('#tools-panel').boundingBox();
    assert(menuBounds.x >= 0 && menuBounds.x + menuBounds.width <= width && menuBounds.y + menuBounds.height <= height,'Tools menu leaves viewport at '+width);
    await page.getByRole('button',{name:'Xem thành viên',exact:true}).click();
    assert(await page.locator('#mobile-member-list .member').count()>=1,'Mobile members missing');
    await page.keyboard.press('Escape');
  }
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'output/playwright/clean-chat-mobile.png'});
  await page.getByRole('heading',{name:'Trò chuyện chung',exact:true}).click();
  const touchMessage = page.locator('.message').last();
  await touchMessage.click();
  assert(await touchMessage.locator('.message-actions').evaluate(node=>getComputedStyle(node).opacity==='1'),'Touch selection did not reveal message actions');
  await touchMessage.getByRole('button',{name:'Trả lời tin nhắn của Alice Nguyen',exact:true}).click();
  assert(await page.locator('#reply-preview').isVisible(),'Reply unavailable on phone');
  await page.getByRole('button',{name:'Hủy trả lời',exact:true}).click();
  await box.fill('');
  check('Thao tác tin trên điện thoại','Chạm tin để mở thao tác, trả lời và hủy được.');
  check('Kích thước màn hình và thành viên','1440, 1024, 768, 390, 320 px: không tràn ngang, dùng được danh sách thành viên.');
  const touchContext = await page.context().browser().newContext({storageState:await page.context().storageState(),viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  try {
    const phone = await touchContext.newPage();
    await phone.goto('http://localhost:8080/chat');
    await phone.waitForFunction(() => document.querySelector('#connection-state')?.dataset.state === 'connected');
    await phone.locator('.message').last().waitFor();
    assert(await phone.evaluate(()=>matchMedia('(hover: none)').matches),'Touch context unexpectedly supports hover');
    await phone.locator('.message').last().tap();
    await phone.locator('.message').last().getByRole('button',{name:'Trả lời tin nhắn của Alice Nguyen',exact:true}).tap();
    assert(await phone.locator('#reply-preview').isVisible(),'Real touch reply failed');
    await phone.getByRole('button',{name:'Hủy trả lời',exact:true}).tap();
    await phone.getByRole('button',{name:'Mở công cụ phòng',exact:true}).tap();
    await phone.getByRole('button',{name:'Xem thành viên',exact:true}).tap();
    assert(await phone.getByRole('dialog').isVisible(),'Real touch menu failed');
    await phone.getByRole('button',{name:'Đóng danh sách thành viên',exact:true}).tap();
    await phone.locator('#room-name').tap();
    await phone.screenshot({path:'output/playwright/clean-chat-touch.png'});
    check('Cảm ứng thực tế','Thiết bị không có hover vẫn chạm để trả lời và mở công cụ/thành viên được.');
  } finally { await touchContext.close(); }
  assert(!errors.length,'Browser JS errors: '+errors.join('; '));
  check('JavaScript trình duyệt','Không có pageerror trong toàn bộ lượt kiểm tra.');
  await page.setViewportSize({width:1440,height:900});
  return {checkedAt:new Date().toISOString(),checks,errors};
}
