async (page) => {
  const base = 'http://localhost:8088', checks = [], errors = [];
  let stage = 'registration';
  const assert = (condition, name) => { if (!condition) throw new Error(name); checks.push(name); };
  const login = async (target, username) => {
    await target.goto(base + '/login');
    await target.getByRole('textbox', { name: 'Tên đăng nhập' }).fill(username);
    await target.getByRole('textbox', { name: 'Mật khẩu', exact: true }).fill('ChatDemo!2026');
    await target.getByRole('button', { name: 'Đăng nhập vào không gian chung' }).click();
    await target.waitForURL('**/chat'); await target.getByText('Đã kết nối', { exact: true }).waitFor();
  };
  const browser = page.context().browser();
  const bobContext = await browser.newContext(), charlieContext = await browser.newContext(), signupContext = await browser.newContext();
  const bob = await bobContext.newPage(), charlie = await charlieContext.newPage(), signup = await signupContext.newPage();
  for (const target of [page, bob, charlie, signup]) target.on('pageerror', error => errors.push(error.message));
  try {
    await page.setViewportSize({ width: 1440, height: 900 });
    await signup.goto(base + '/register');
    await signup.getByRole('textbox', { name: 'Tên đăng nhập' }).fill('qa_browser_user');
    await signup.getByRole('textbox', { name: 'Tên hiển thị' }).fill('QA Browser User');
    await signup.getByRole('textbox', { name: 'Mật khẩu' }).fill('qa-browser-password-2026');
    await signup.getByRole('button', { name: 'Tạo tài khoản' }).click();
    await signup.waitForURL('**/chat'); await signup.getByText('Đã kết nối', { exact: true }).waitFor();
    assert(await signup.locator('#self-name').textContent() === 'QA Browser User', 'Registration creates a signed-in user through the UI');
    stage = 'friends and direct messages';
    await login(page, 'alice'); await login(bob, 'bob'); await login(charlie, 'charlie');

    await page.getByRole('button', { name: /♧ Bạn bè/ }).click();
    await page.getByRole('searchbox', { name: 'Tìm bạn bè' }).fill('bob');
    const bobRow = page.getByRole('listitem').filter({ hasText: '@bob' });
    await bobRow.getByRole('button', { name: 'Kết bạn +' }).click();
    await bobRow.getByText('Đã gửi lời mời', { exact: true }).waitFor();
    await bob.getByRole('button', { name: /♧ Bạn bè/ }).click();
    assert(await bob.locator('[data-people-mode="nearby"], [data-people-mode="random"], #location-panel').count() === 0, 'Nearby and random features are absent from the friend dialog');
    await bob.getByRole('button', { name: 'Lời mời', exact: true }).click();
    await bob.getByRole('listitem').filter({ hasText: '@alice' }).getByRole('button', { name: 'Chấp nhận' }).waitFor();
    await bob.getByRole('listitem').filter({ hasText: '@alice' }).getByRole('button', { name: 'Chấp nhận' }).click();
    await bob.getByRole('button', { name: 'Đóng bạn bè' }).click();
    await page.getByRole('button', { name: 'Làm mới danh sách bạn bè' }).click();
    await page.getByRole('listitem').filter({ hasText: '@bob' }).getByRole('button', { name: 'Nhắn tin' }).click();
    await page.getByRole('heading', { name: 'Trò chuyện với Bob Tran', exact: true }).waitFor();
    const roomsWithDirect = (await (await page.request.get(base + '/api/rooms')).json()).data;
    const directRoom = roomsWithDirect.find(room => room.name === 'Trò chuyện với Bob Tran');
    assert(Boolean(directRoom?.direct), 'Friend row opens a private one-to-one room');
    const directMessage = 'Tin nhắn riêng từ Alice';
    await page.getByRole('textbox', { name: 'Tin nhắn của bạn' }).fill(directMessage);
    await page.getByRole('button', { name: 'Gửi tin nhắn' }).click();
    await page.getByRole('log').getByText(directMessage, { exact: true }).waitFor();
    await bob.getByRole('button', { name: /Trò chuyện với Alice Nguyen/ }).waitFor({ timeout: 8000 });
    await bob.getByRole('button', { name: /Trò chuyện với Alice Nguyen/ }).click();
    await bob.getByRole('log').getByText(directMessage, { exact: true }).waitFor();
    assert((await charlie.request.get(`${base}/api/rooms/${directRoom.id}/messages`)).status() === 404, 'An outsider cannot read a direct conversation');
    checks.push('Direct message is delivered and visible to both friends');

    await page.getByRole('button', { name: '♧ Bạn bè' }).click();
    await page.getByRole('searchbox', { name: 'Tìm bạn bè' }).fill('charlie');
    const charlieRow = page.getByRole('listitem').filter({ hasText: '@charlie' });
    await charlieRow.getByRole('button', { name: 'Kết bạn +' }).click();
    await charlie.getByRole('button', { name: '♧ Bạn bè' }).click();
    await charlie.getByRole('listitem').filter({ hasText: '@alice' }).getByText('Đã gửi lời mời', { exact: true }).waitFor();
    await charlie.getByRole('listitem').filter({ hasText: '@alice' }).getByRole('button', { name: 'Chấp nhận' }).click();
    await page.getByRole('button', { name: 'Đóng bạn bè' }).click();
    stage = 'group creation and management';
    await page.getByRole('button', { name: '＋ Tạo nhóm' }).click();
    const originalGroup = 'Nhóm QA ' + Date.now();
    await page.locator('#group-name').fill(originalGroup);
    await page.getByRole('checkbox', { name: /Bob Tran/ }).check();
    await page.getByRole('button', { name: 'Tạo nhóm ↗', exact: true }).click();
    stage = 'group created';
    await page.getByRole('heading', { name: originalGroup, exact: true }).waitFor();
    const roomList = (await (await page.request.get(base + '/api/rooms')).json()).data;
    const group = roomList.find(room => room.name === originalGroup);
    assert(Boolean(group?.isOwner), 'Group creator is identified as the owner');
    await page.getByRole('button', { name: 'Mở công cụ phòng' }).click();
    await page.getByRole('button', { name: 'Quản lý nhóm' }).click();
    await page.locator('#manage-group-name').fill('Nhóm QA đã đổi tên');
    stage = 'rename group submitted';
    await page.getByRole('button', { name: 'Lưu tên nhóm' }).click();
    stage = 'wait for renamed room title';
    await page.waitForFunction(() => document.querySelector('#room-name')?.textContent === 'Nhóm QA đã đổi tên');
    stage = 'group renamed';
    await page.locator('#add-group-member').selectOption({ label: 'Charlie Le' });
    stage = 'member selected';
    await page.locator('#add-group-member-submit').click();
    stage = 'member added';
    await page.getByRole('listitem').filter({ hasText: '@charlie' }).waitFor();
    await page.getByRole('button', { name: 'Đóng quản lý nhóm' }).click();
    stage = 'wait for invited member room list';
    await charlie.reload(); await charlie.getByText('Đã kết nối', { exact: true }).waitFor();
    await charlie.getByRole('button', { name: /Nhóm QA đã đổi tên/ }).waitFor({ timeout: 15000 });
    await charlie.getByRole('button', { name: /Nhóm QA đã đổi tên/ }).click();
    stage = 'wait for invited member room to load';
    await charlie.getByRole('heading', { name: 'Nhóm QA đã đổi tên', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Mở công cụ phòng' }).click();
    await page.getByRole('button', { name: 'Quản lý nhóm' }).click();
    await page.getByRole('listitem').filter({ hasText: '@charlie' }).getByRole('button', { name: 'Xóa khỏi nhóm' }).click();
    await page.getByRole('listitem').filter({ hasText: '@charlie' }).waitFor({ state: 'detached' });
    await charlie.reload(); await charlie.getByText('Đã kết nối', { exact: true }).waitFor();
    await charlie.getByRole('heading', { name: 'Trò chuyện chung', exact: true }).waitFor({ timeout: 10000 });
    assert((await charlie.request.get(`${base}/api/rooms/${group.id}/messages`)).status() === 404, 'Removed group member loses history and returns to an allowed room');
    await bob.reload(); await bob.getByText('Đã kết nối', { exact: true }).waitFor();
    await bob.getByRole('button', { name: /Nhóm QA đã đổi tên/ }).click();
    await bob.getByRole('button', { name: 'Mở công cụ phòng' }).click();
    await bob.getByRole('button', { name: 'Quản lý nhóm' }).click();
    bob.once('dialog', dialog => dialog.accept());
    await bob.getByRole('button', { name: 'Rời nhóm' }).click();
    await bob.getByRole('heading', { name: 'Trò chuyện chung', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Đóng quản lý nhóm' }).click();
    await page.getByRole('button', { name: 'Mở công cụ phòng' }).click();
    await page.getByRole('button', { name: 'Quản lý nhóm' }).click();
    page.once('dialog', dialog => dialog.accept());
    await page.getByRole('button', { name: 'Xóa nhóm' }).click();
    await page.getByRole('button', { name: /Nhóm QA đã đổi tên/ }).waitFor({ state: 'detached' });
    assert((await page.request.get(`${base}/api/rooms/${group.id}/messages`)).status() === 404, 'Owner can delete a group and its history');
    assert(true, 'Group rename, member addition/removal, member leave and owner deletion are available in the UI');

    stage = 'history, search, and export';
    await page.getByRole('button', { name: '# Kỹ thuật', exact: true }).click();
    await page.getByRole('button', { name: 'Tải tin nhắn cũ hơn' }).waitFor();
    await page.getByRole('button', { name: 'Tải tin nhắn cũ hơn' }).click();
    await page.getByRole('button', { name: 'Tải tin nhắn cũ hơn' }).click();
    await page.getByRole('log').getByText('QA history 005 old anchor marker', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Tìm tin nhắn' }).click();
    await page.getByRole('searchbox', { name: 'Tìm tin nhắn' }).fill('anchor marker');
    await page.getByRole('log').getByText('QA history 005 old anchor marker', { exact: true }).waitFor();
    assert(true, 'Older history can be paged and an old message can be found by full-history search');
    const [download] = await Promise.all([
      page.waitForEvent('download'),
      (async () => { await page.getByRole('searchbox', { name: 'Tìm tin nhắn' }).fill(''); await page.getByRole('button', { name: 'Đóng tìm kiếm' }).click(); await page.getByRole('button', { name: 'Mở công cụ phòng' }).click(); await page.getByRole('button', { name: 'Xuất hội thoại' }).click(); })()
    ]);
    await page.getByText(/Đã xuất toàn bộ 121 tin nhắn/).waitFor();
    assert(download.suggestedFilename().endsWith('.txt'), 'Full-history export downloads a UTF-8 text file');

    stage = 'draft persistence and responsive layout';
    await page.getByRole('button', { name: '# Trò chuyện chung', exact: true }).click();
    const composer = page.getByRole('textbox', { name: 'Tin nhắn của bạn' });
    await composer.fill('Bản nháp qua lần đóng thẻ'); await page.reload(); await page.getByText('Đã kết nối', { exact: true }).waitFor();
    assert(await composer.inputValue() === 'Bản nháp qua lần đóng thẻ', 'Draft survives a full page reload');
    await composer.fill('');
    await page.locator('.message').last().hover();
    await page.locator('.message').last().getByRole('button', { name: /Sao chép tin nhắn của/ }).click();
    await page.waitForFunction(() => !document.querySelector('#toast').hidden);
    await page.setViewportSize({ width: 390, height: 844 });
    const toastBox = await page.locator('#toast').boundingBox(), composerBox = await page.locator('.composer-area').boundingBox();
    const intersects = toastBox.x < composerBox.x + composerBox.width && toastBox.x + toastBox.width > composerBox.x && toastBox.y < composerBox.y + composerBox.height && toastBox.y + toastBox.height > composerBox.y;
    assert(!intersects, 'Toast no longer covers the mobile composer');
    await page.waitForFunction(() => document.querySelector('#toast').hidden, null, { timeout: 5000 });
    const mobileFits = await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth);
    await page.setViewportSize({ width: 1440, height: 900 });
    const desktopFits = await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth);
    assert(mobileFits && desktopFits, 'Updated chat fits mobile and desktop viewports');
    assert(errors.length === 0, 'No browser JavaScript errors in the full workflow');
    const result = { checkedAt: new Date().toISOString(), checks, errors };
    await page.evaluate(value => { document.body.dataset.qaResult = JSON.stringify(value); }, result);
    return result;
  } catch (error) {
    const result = { checkedAt: new Date().toISOString(), stage, checks, errors, failure: error.message };
    await page.evaluate(value => { document.body.dataset.qaResult = JSON.stringify(value); }, result).catch(() => {});
    return result;
  }
  finally { await bobContext.close(); await charlieContext.close(); await signupContext.close(); }
}
